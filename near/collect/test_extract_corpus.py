import tempfile
import unittest
from pathlib import Path

from near.collect.extract_corpus import (body_stats, dedupe, drop_reason, is_sdk_copy, is_trivial, norm_code,
                                         norm_hash, repo_samples, vulnerable_refs)

SETTER = "pub fn set_owner(&mut self, owner: AccountId) {\n    self.owner = owner;\n}\n"
GUARDED = ("pub fn set_owner(&mut self, owner: AccountId) {\n    self.assert_owner();\n    self.owner = owner;\n}\n")
MATCH = ("fn kind(&self, x: u8) -> u8 {\n    match x {\n        0 => {\n            log!(\"a\");\n            1\n"
         "        }\n        _ => 2,\n    }\n}\n")


class NormCodeTest(unittest.TestCase):
    def test_strips_comments_and_whitespace(self):
        a = "/// doc\n#[payable]\npub fn f(&mut self) {\n    // note\n    let x = 1; /* inline */\n    x\n}\n"
        self.assertEqual(norm_code(a), "#[payable] pub fn f(&mut self) { let x = 1; x }")

    def test_keeps_comment_markers_in_strings(self):
        self.assertIn('"http://x"', norm_code('fn f() { let u = "http://x"; u }'))

    def test_hash_ignores_formatting_only(self):
        self.assertEqual(norm_hash(GUARDED), norm_hash(GUARDED.replace("    ", "\t") + "// trailing\n"))
        self.assertNotEqual(norm_hash(GUARDED), norm_hash(SETTER))


class TrivialTest(unittest.TestCase):
    def test_body_stats(self):
        self.assertEqual(body_stats(SETTER), (1, 3))
        self.assertEqual(body_stats(GUARDED), (2, 4))
        self.assertEqual(body_stats("fn get(&self) -> u64 { self.x }"), (1, 1))

    def test_nested_blocks_count(self):
        self.assertEqual(body_stats(MATCH)[0], 3)  # match expr + log! + trailing 1 in the arm block

    def test_is_trivial(self):
        self.assertTrue(is_trivial(SETTER))
        self.assertTrue(is_trivial("fn f() { a(); b(); }"))  # one line
        self.assertFalse(is_trivial(GUARDED))
        self.assertFalse(is_trivial(MATCH))


class DropReasonTest(unittest.TestCase):
    def test_paths(self):
        self.assertIsNone(drop_reason("contracts/ft/src/lib.rs", "a/b", False))
        self.assertEqual(drop_reason("x/target/debug/build/out.rs", "a/b", False), "generated")
        self.assertEqual(drop_reason("vendor/borsh/src/lib.rs", "a/b", False), "vendored")
        self.assertEqual(drop_reason("vendors/near-sdk/src/lib.rs", "a/b", False), "vendored")
        self.assertEqual(drop_reason("near-sdk/src/environment/env.rs", "a/b", False), "near_sdk_internal")
        self.assertEqual(drop_reason("lib/near-sdk-rs/examples/x/src/lib.rs", "a/b", False), "near_sdk_internal")
        self.assertEqual(drop_reason("near-contract-standards/src/fungible_token/core_impl.rs", "a/b", False),
                         "near_sdk_internal")

    def test_generated_and_versioned_sdk_copies(self):
        self.assertEqual(drop_reason("near/res/fastbridge_expand.rs", "a/b", False), "generated")
        self.assertEqual(drop_reason("src/lib.rs", "a/b", False, "// @generated by tool\nfn a() {}"), "generated")
        spiral = "#![allow(unused_mut, unused_variables, unused_imports, unused_parens, dead_code)]\nuse std::rc::Rc;"
        self.assertEqual(drop_reason("apps/spiral/spiral.rs", "a/b", False, spiral), "generated")
        self.assertIsNone(drop_reason("src/lib.rs", "a/b", False, "#![allow(dead_code)]\n// automatically generated getters"))
        self.assertEqual(drop_reason("docs/sources/near-sdk-5.30.1/src/lib.rs", "a/b", False), "near_sdk_internal")
        self.assertEqual(drop_reason("x/near-contract-standards-3.2.0/src/lib.rs", "a/b", False), "near_sdk_internal")

    def test_canonical_sdk_keeps_standards_and_examples(self):
        self.assertIsNone(drop_reason("near-contract-standards/src/fungible_token/core_impl.rs", "near/near-sdk-rs", False))
        self.assertIsNone(drop_reason("examples/fungible-token/ft/src/lib.rs", "near/near-sdk-rs", False))
        self.assertEqual(drop_reason("near-sdk/src/lib.rs", "near/near-sdk-rs", False), "near_sdk_internal")

    def test_sdk_copy_drops_examples(self):
        self.assertEqual(drop_reason("examples/fungible-token/ft/src/lib.rs", "x/near-sdk-rs", True), "near_sdk_internal")
        self.assertIsNone(drop_reason("src/lib.rs", "x/dao", True))

    def test_security_demos(self):
        self.assertEqual(drop_reason("examples/reentrancy/src/lib.rs", "blocksecteam/rustle", False), "security_demo")
        self.assertEqual(drop_reason("src/lib.rs", "Shenyimings/FORGE-S-Artifacts", False), "security_demo")
        for p in ["fixtures/pf001_callback/vulnerable/src/lib.rs", "exploit-stub/src/lib.rs", "vaults/buggy/src/lib.rs",
                  "helpers/evil-receiver/src/lib.rs", "contracts/contract_unsafe/src/lib.rs", "phishing/attack/src/lib.rs",
                  "tests/source/fixtures/safe/lib.rs", "x/test-fixtures/near/a.rs"]:
            self.assertEqual(drop_reason(p, "a/b", False), "security_demo", p)
        for p in ["contracts/ctf/src/lib.rs", "src/attack_surface.rs", "contracts/unsafe_math_lib/src/lib.rs"]:
            self.assertIsNone(drop_reason(p, "a/b", False), p)

    def test_is_sdk_copy(self):
        self.assertTrue(is_sdk_copy(["near-sdk/src/lib.rs", "src/lib.rs"], "x/fork"))
        self.assertFalse(is_sdk_copy(["near-sdk/src/lib.rs"], "near/near-sdk-rs"))
        self.assertFalse(is_sdk_copy(["contracts/near-sdk/src/lib.rs"], "x/y"))


class DedupeTest(unittest.TestCase):
    def test_keeps_most_starred_then_earliest(self):
        rows = [{"norm_hash": "h", "group": "a/x", "stars": 1, "date": "2021-01-01", "path": "p", "start_line": 1},
                {"norm_hash": "h", "group": "b/y", "stars": 9, "date": "2023-01-01", "path": "p", "start_line": 1},
                {"norm_hash": "h", "group": "c/z", "stars": 9, "date": "2022-01-01", "path": "p", "start_line": 1},
                {"norm_hash": "k", "group": "a/x", "stars": 1, "date": "2021-01-01", "path": "p", "start_line": 5}]
        kept = {r["norm_hash"]: r for r in dedupe(rows)}
        self.assertEqual(kept["h"]["group"], "c/z")
        self.assertEqual((kept["h"]["dup_count"], kept["h"]["dup_repos"]), (3, 3))
        self.assertEqual((kept["k"]["dup_count"], kept["k"]["dup_repos"]), (1, 1))


class VulnerableRefsTest(unittest.TestCase):
    def test_refs_from_all_sources(self):
        audits = [{"repo": "https://github.com/A/B", "commit": "c1", "path": "src/x. rs", "fn": "Pool::swap"},
                  {"repo": "https://github.com/A/B", "commit": None, "path": "src/x.rs", "fn": "f"},
                  {"repo": "https://github.com/A/B", "commit": "c1", "path": "src/x.rs", "fn": None}]
        fixes = [{"repo": "c/d", "parent": "p1", "files": ["src/lib.rs", "tests/t.rs"], "fns": ["g", "h"]}]
        incidents = [{"repo": "https://github.com/e/f", "vuln_commit": None, "fix_commit": "f1", "path": "a.rs", "fn": "k"},
                     {"repo": "https://github.com/e/f", "vuln_commit": "v1", "fix_commit": "f2", "path": "a.rs", "fn": "m"},
                     {"repo": None, "vuln_commit": None, "fix_commit": None, "path": None, "fn": "z"}]
        self.assertEqual(sorted(vulnerable_refs(audits, fixes, incidents)), [
            ("a/b", "c1", "src/x.rs", "swap"), ("c/d", "p1", "src/lib.rs", "g"), ("c/d", "p1", "src/lib.rs", "h"),
            ("c/d", "p1", "tests/t.rs", "g"), ("c/d", "p1", "tests/t.rs", "h"),
            ("e/f", "f1^", "a.rs", "k"), ("e/f", "v1", "a.rs", "m")])


class RepoSamplesTest(unittest.TestCase):
    def test_extracts_contract_files_only(self):
        src = ("use near_sdk::{near, env, AccountId};\n#[near(contract_state)]\npub struct C { owner: AccountId }\n"
               "#[near]\nimpl C {\n" + "\n".join("    " + l for l in GUARDED.splitlines()) + "\n"
               "    pub fn get(&self) -> AccountId { self.owner.clone() }\n}\n"
               "#[cfg(test)]\nmod tests {\n    #[test]\n    fn t() {\n        let a = 1;\n        assert_eq!(a, 1);\n    }\n}\n")
        with tempfile.TemporaryDirectory() as d:
            (Path(d) / "src").mkdir()
            (Path(d) / "src/lib.rs").write_text(src)
            (Path(d) / "src/util.rs").write_text("fn helper() {\n    a();\n    b();\n}\n")
            meta = {"repo": "Owner/Repo", "stars": 3, "audited": False, "head_commit": "abc", "last_commit": "2024-02-03",
                    "local_path": d}
            rows, stats = repo_samples(meta)
        self.assertEqual(stats["contract_files"], 1)
        self.assertEqual((stats["fns"], stats["test"], stats["trivial"]), (3, 1, 1))
        self.assertEqual(len(rows), 1)
        r = rows[0]
        self.assertEqual((r["fn"], r["impl"], r["is_near_bindgen"], r["is_public"]), ("set_owner", "C", True, True))
        self.assertEqual((r["label"], r["source"], r["group"], r["commit"], r["date"]), (0, "corpus", "owner/repo", "abc", "2024-02-03"))
        self.assertEqual((r["path"], r["n_lines"], r["vuln_class"], r["pair_id"]), ("src/lib.rs", 4, None, None))
        self.assertEqual(r["evidence"], "https://github.com/Owner/Repo/blob/abc/src/lib.rs#L6-L9")
        self.assertNotIn("is_test", r)


